# ============================================================
# §6.2.1 重载速度惩罚 —— 载重比例（货重/车辆载重上限）越高，行驶越慢
# ============================================================
# 阈值必须按从小到大排列；最后一档用 float("inf") 兜底“超过前面所有阈值”的情况。
速度惩罚阈值表: list[tuple[float, float]] = [
    (0.5, 1.00),  # 载重比例 <= 0.5 （轻载）-> 正常速度
    (0.8, 1.15),  # 0.5 < 载重比例 <= 0.8 （中载）-> 慢 15%
    (float("inf"), 1.25),  # 载重比例 > 0.8 （重载）-> 慢 25%
]


def 速度系数(载重比例: float) -> float:
    for 阈值, 系数 in 速度惩罚阈值表:
        if 载重比例 <= 阈值:
            return 系数
    return 速度惩罚阈值表[-1][1]


# ============================================================
# §6.2.2 强制休息时间（越南交规估算值，非官方数值，仅供参考）
# ============================================================
每次连续驾驶小时数 = 4  # 每连续驾驶这么多小时，强制休息一次
每次强制休息小时数 = 0.5
单日过夜阈值小时数 = 8  # 调整后的行驶时长超过这个数，需要过夜休息
过夜休息小时数 = 8


def 休息时长(调整后行驶小时数: float) -> float:
    休息总时长 = 0.0
    剩余小时数 = 调整后行驶小时数
    while 剩余小时数 > 每次连续驾驶小时数:
        休息总时长 += 每次强制休息小时数
        剩余小时数 -= 每次连续驾驶小时数
    if 调整后行驶小时数 > 单日过夜阈值小时数:
        休息总时长 += 过夜休息小时数
    return 休息总时长


# ============================================================
# §6.2.3 装卸时间
# ============================================================
每吨装卸小时数 = 0.5


def 装卸时长(货物重量吨: float, 需要装卸: bool) -> float:
    return 货物重量吨 * 每吨装卸小时数 if 需要装卸 else 0.0


# ============================================================
# §6.2.4 总用时 —— 由上述各子项组装，正算和反算共用
# ============================================================
def 计算总用时(
    *,
    载重比例: float,
    原始行驶小时: float,
    货物重量吨: float,
    需要装卸: bool,
) -> tuple[float, float, float, float, float]:
    """组装完整的时间链，返回 (速度系数, 调整后行驶小时, 休息小时, 装卸小时, 总用时小时)。

    正算（cost_engine）和反算（calibration）都调用这个函数，
    保证两边对"一段行程需要多少时间"的计算逻辑完全一致。
    """
    sf = 速度系数(载重比例)
    adjusted = 原始行驶小时 * sf
    rest = 休息时长(adjusted)
    loading = 装卸时长(货物重量吨, 需要装卸)
    return sf, adjusted, rest, loading, adjusted + rest + loading


# ============================================================
# §6.3.0 拼货容量占比（仅拼货/consolidated 模式使用）
# ============================================================
def 容量占比(货物重量吨: float, 货物体积立方米: float | None,
             车型最大载重吨: float, 车型容积立方米: float | None) -> float:
    """拼货场景下，这批货占用了匹配车型的多大比例运力——按重量比和体积比取较大值
    （哪个先"装满"就按哪个算），车型没有容积上限（如平板车）时只看重量比。

    整车模式不调用这个函数，capacity_ratio 恒为 1.0，等价于本函数返回值恒为1的特例。
    """
    weight_ratio = 货物重量吨 / 车型最大载重吨 if 车型最大载重吨 else 0.0
    if 车型容积立方米 is None or 货物体积立方米 is None:
        return weight_ratio
    volume_ratio = 货物体积立方米 / 车型容积立方米 if 车型容积立方米 else 0.0
    return max(weight_ratio, volume_ratio)


# ============================================================
# §6.3.0b 所需车辆数 —— 四约束取最大值（2026-08-09 新增）
# ============================================================
# 车辆数 = max(
#     ① 重量约束: ceil(总重量 / 车型载重)
#     ② 体积约束: ceil(总体积 / (车型容积 × 装载效率))
#     ③ 长度约束: ceil(最大单件长 / 车型地板长)   ← 不可分割的长件
#     ④ 面积约束: ceil(总面积 / (车型地板面积 × 装载效率))  ← 不可堆叠的异形件
# )
# 装载效率 (loading_efficiency)：异形货物/绑扎间隙浪费的空间，默认 0.9。
# 平板车无厢内容积时用 地板面积 × 最大堆高 作为等效容积（effective_volume）。

def 所需车辆数(
    *,
    货物总重量吨: float,
    货物总体积立方米: float | None,
    最大单件长度米: float | None,
    货物总占地面积平方米: float | None,
    车型最大载重吨: float,
    车型容积立方米: float | None,
    车型地板长米: float | None,
    车型地板面积平方米: float | None,
    装载效率: float = 0.90,
) -> int:
    """计算运输这批货物需要几辆车（各约束取最大值，至少 1 辆）。

    所有约束都只对"单车能装多少"负责：
    - 重量：整车载重上限
    - 体积：厢内容积（或平板等效容积）× 装载效率
    - 长度：不可分割单件的最大长度 vs 车厢地板长度
    - 面积：不可堆叠件的地板投影面积 vs 地板面积 × 装载效率
    """
    return 车辆数分解(
        货物总重量吨=货物总重量吨, 货物总体积立方米=货物总体积立方米,
        最大单件长度米=最大单件长度米, 货物总占地面积平方米=货物总占地面积平方米,
        车型最大载重吨=车型最大载重吨, 车型容积立方米=车型容积立方米,
        车型地板长米=车型地板长米, 车型地板面积平方米=车型地板面积平方米,
        装载效率=装载效率,
    )["车数"]


def 车辆数分解(
    *,
    货物总重量吨: float,
    货物总体积立方米: float | None,
    最大单件长度米: float | None,
    货物总占地面积平方米: float | None,
    车型最大载重吨: float,
    车型容积立方米: float | None,
    车型地板长米: float | None,
    车型地板面积平方米: float | None,
    装载效率: float = 0.90,
    最大单件重量吨: float | None = None,
) -> dict:
    """🆕 四约束车辆数分解：返回各约束推算的车数、总车数、主因（供前端任务卡预览「为什么 N 辆」）。

    🆕 2026-09-20 新增「不可分超载」判定：某一件货物自身重量 > 车型载重时，
    该车型根本装不下这一件 —— 多派几辆普通车解决不了（越南公路 >38t 属超限运输，
    需特种车 + 超限许可）。此时 `不可分=True`、`主因="单件超载不可分"`，
    调用方（API 层）应按「超限单」处置，不得静默按车数拆算出假价。
    """
    import math

    w = math.ceil(货物总重量吨 / 车型最大载重吨) if (车型最大载重吨 and 车型最大载重吨 > 0) else 0
    vol = math.ceil(货物总体积立方米 / (车型容积立方米 * 装载效率)) if (货物总体积立方米 and 车型容积立方米 and 车型容积立方米 > 0) else 0
    ln = math.ceil(最大单件长度米 / 车型地板长米) if (最大单件长度米 and 车型地板长米 and 车型地板长米 > 0) else 0
    area = math.ceil(货物总占地面积平方米 / (车型地板面积平方米 * 装载效率)) if (货物总占地面积平方米 and 车型地板面积平方米 and 车型地板面积平方米 > 0) else 0
    # 🆕 不可分超载：单件重量 > 车型载重（该车型不适用，不能靠多派车解决）
    不可分 = bool(
        最大单件重量吨 and 车型最大载重吨 and 最大单件重量吨 > 车型最大载重吨 + 1e-9
    )
    # 至少 1 辆
    n = max(1, w, vol, ln, area)
    part = {"重量": w, "体积": vol, "长度": ln, "面积": area}
    活跃 = {k: v for k, v in part.items() if v > 0}
    主因 = "单件超载不可分" if 不可分 else (max(活跃, key=lambda k: 活跃[k]) if 活跃 else "重量")
    return {
        "车数": n, "重量": w, "体积": vol, "长度": ln, "面积": area, "主因": 主因,
        "不可分": 不可分,                     # 单件超载 → 该车型不可用（API 层据此拦截）
        "最大单件重量吨": 最大单件重量吨,
        "车型最大载重吨": 车型最大载重吨,
    }


def 货物载荷特征(
    *,
    货物总重量吨: float,
    货物总体积立方米: float | None,
    单件货物: list[dict] | None = None,
) -> tuple[float | None, float | None]:
    """从单件货物明细汇总出（最大单件长度, 总占地面积）。

    规则：
    - 最大单件长度 = 所有单件 length_m 的最大值（不可分割长件约束）
    - 总占地面积 = 所有"不可堆叠"单件的 长×宽×件数 之和
      （可堆叠货物按体积计，不占用地板面积）
    - 不提供单件明细时返回 (None, None) —— 调用方回退到 Level 1（仅重量+体积）

    单件货物元素格式: {"count": int, "length_m": float, "width_m": float,
                       "height_m": float, "weight_kg": float, "stackable": bool}
    """
    f = 货物载荷特征完整(
        货物总重量吨=货物总重量吨, 货物总体积立方米=货物总体积立方米, 单件货物=单件货物,
    )
    return f["最大单件长度米"], f["总占地面积平方米"]


def 货物载荷特征完整(
    *,
    货物总重量吨: float,
    货物总体积立方米: float | None,
    单件货物: list[dict] | None = None,
) -> dict:
    """🆕 单件明细 → {最大单件长度米, 总占地面积平方米, 最大单件重量吨}。

    - 最大单件长度：所有单件 length_m 最大值（不可分割长件约束）
    - 总占地面积：所有"不可堆叠"单件的 长×宽×件数 之和
    - 最大单件重量：所有单件 weight_kg 最大值 / 1000（🆕 不可分超载判定用）
    - 无单件明细时三者皆 None（调用方回退仅重量+体积）
    """
    if not 单件货物:
        return {"最大单件长度米": None, "总占地面积平方米": None, "最大单件重量吨": None}

    最大单件长 = 0.0
    占地面积 = 0.0
    最大单件重吨 = 0.0
    for item in 单件货物:
        长 = float(item.get("length_m") or 0)
        宽 = float(item.get("width_m") or 0)
        件数 = int(item.get("count") or 1)
        可堆叠 = bool(item.get("stackable", True))
        单件重吨 = float(item.get("weight_kg") or 0) / 1000.0
        最大单件长 = max(最大单件长, 长)
        最大单件重吨 = max(最大单件重吨, 单件重吨)
        if not 可堆叠 and 长 > 0 and 宽 > 0:
            占地面积 += 长 * 宽 * 件数
    return {
        "最大单件长度米": 最大单件长 or None,
        "总占地面积平方米": 占地面积 or None,
        "最大单件重量吨": 最大单件重吨 or None,
    }


# ============================================================
# §6.3.1 距离成本（基础运费）
# ============================================================
空车返回附加比例 = 0.5  # 空车返回时，返程按这个比例的距离成本计入


def 距离成本(距离公里: float, 车辆基础费率: float, 货物类型系数: float, 空车返回: bool) -> float:
    返程系数 = 空车返回附加比例 if 空车返回 else 0.0
    return 距离公里 * 车辆基础费率 * 货物类型系数 * (1 + 返程系数)


# ============================================================
# §6.3.2 时间成本
# ============================================================
def 时间成本(总用时小时数: float, 司机小时工资: float) -> float:
    return 总用时小时数 * 司机小时工资


# ============================================================
# §6.3.3 油耗成本（含载重油耗修正）
# ============================================================
油耗修正起始比例 = 0.5  # 载重比例超过这个值才开始增加油耗
油耗修正斜率 = 0.2  # 每超出 起始比例 1.0（即100%），油耗增加这个比例


def 油耗载重系数(载重比例: float) -> float:
    if 载重比例 <= 油耗修正起始比例:
        return 1.0
    return 1.0 + 油耗修正斜率 * (载重比例 - 油耗修正起始比例)


def 油耗成本(距离公里: float, 百公里油耗: float, 油价: float, 载重比例: float, 货物油耗附加比例: float) -> float:
    每公里油耗 = 百公里油耗 / 100
    return 距离公里 * 每公里油耗 * 油价 * 油耗载重系数(载重比例) * (1 + 货物油耗附加比例)


