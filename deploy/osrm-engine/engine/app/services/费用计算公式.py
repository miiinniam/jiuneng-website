港口附加比例 = 0.75  # 港口目的地附加费 = 固定调度费 × 此比例


def 港口附加费(固定调度费: float, 是否港口目的地: bool) -> float:
    return 固定调度费 * 港口附加比例 if 是否港口目的地 and 固定调度费 > 0 else 0.0


