# §6.3.4 固定费用
# ============================================================
def 装卸费(货物重量吨: float, 每吨装卸费率: float, 需要装卸: bool) -> float:
    return 货物重量吨 * 每吨装卸费率 if 需要装卸 else 0.0


def 保险费(货值: float | None, 保险费率: float) -> float:
    return 货值 * 保险费率 if 货值 else 0.0


def 路桥费(距离公里: float, 路桥费率: float) -> float:
    return 距离公里 * 路桥费率


def 车身附加费(车身固定附加费: float) -> float:
    """车身类型自带的固定附加费（比如冷链机组维护），跟距离/重量无关，每趟固定收一次。"""
    return 车身固定附加费


# ============================================================
# §6.3.4.1 港口目的地附加费（2026-07-16 新增）
# ============================================================
# 海防/广宁等港口区域有显著的额外成本（拥堵、特种装卸、单据费），
