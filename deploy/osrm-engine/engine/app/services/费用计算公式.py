def 禁限行绕行费(基础费: float, 类型系数: float, 需要绕开禁限行: bool) -> float:
    return 基础费 * 类型系数 if 需要绕开禁限行 else 0.0


def 施工封闭绕行费(基础费: float, 类型系数: float, 需要绕开施工封闭: bool) -> float:
    return 基础费 * 类型系数 if 需要绕开施工封闭 else 0.0


def 上坡山区附加费(基础费: float, 类型系数: float, 途经上坡山区: bool) -> float:
    return 基础费 * 类型系数 if 途经上坡山区 else 0.0


# ============================================================
# §6.3.5 整车总成本 —— 一口价模式，不拆分油耗/时间
# ============================================================
# 整车运输的报价逻辑与拼车不同：供应商报的是"一趟车从A到B总共多少钱"，
# 这个价格已经包含了距离/油耗/司机工资/路桥等全部成本。正算公式只需：
#   距离 × 基价（全包每公里费率）+ 各项附加费
# 不需要像拼车那样把油耗、时间、距离拆成三项分别计算。
#
# 基价每公里 来自 车辆型号库.csv 的 base_rate_vnd_per_km 列——
# 这个数字本身就是通过供应商真实报价反算出来的全包费率（见 calibration.py）。
def 整车总成本(
    *,
    距离公里: float,
    基价每公里: float,         # 从车辆型号库.csv 标定好的全包费率
    货物类型系数: float,
    空车返回: bool,
    路桥费_vnd: float,
    车身附加费_vnd: float,
    禁限行附加: float,
    施工封闭附加: float,
    上坡山区附加: float,
    港口附加: float,
    装卸费_vnd: float,
    保险费_vnd: float,
    杂费_vnd: float,
) -> float:
    return (
        距离成本(距离公里, 基价每公里, 货物类型系数, 空车返回)
        + 路桥费_vnd
        + 车身附加费_vnd
        + 禁限行附加
        + 施工封闭附加
        + 上坡山区附加
        + 港口附加
        + 装卸费_vnd
        + 保险费_vnd
        + 杂费_vnd
    )
